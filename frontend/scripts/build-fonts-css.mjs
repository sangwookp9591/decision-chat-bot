// Builds src/styles/pretendard-subset.css from the upstream Pretendard Variable dynamic-subset CSS.
// Keeps the unicode-range slicing (browsers download only the slices a page uses) but ships fewer faces and a narrower weight range:
//   - weight 400–700 (the UI uses 400/500/600/700; the upstream declares 45–920)
//   - slices: 72–91 (the frequency tiers that hold the common Hangul + Latin) plus every slice holding a non-ASCII character that
//     appears in src/ (symbols, arrows, rarer syllables). Rare Hangul outside those fall back to the system Korean font.
// Run from frontend/: node scripts/build-fonts-css.mjs   (src/styles/fonts.test.ts checks the result covers the app's characters)
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const upstream = 'node_modules/pretendard/dist/web/variable/pretendardvariable-dynamic-subset.css';
const css = readFileSync(upstream, 'utf8');
const faces = [...css.matchAll(/\/\* \[(\d+)\] \*\/[\s\S]*?unicode-range: ([^;]*);/g)].map((m) => ({ index: +m[1], range: m[2].replace(/\s+/g, ' ').trim() }));
const parse = (range) => range.split(',').map((s) => s.trim().replace('U+', '').split('-').map((h) => parseInt(h, 16)));
const has = (face, cp) => parse(face.range).some(([a, b]) => cp >= a && cp <= (b ?? a));
function walk(dir, out = []) { for (const n of readdirSync(dir)) { const p = join(dir, n); if (statSync(p).isDirectory()) walk(p, out); else if (/\.(tsx?|css)$/.test(n) && !/\.test\./.test(n)) out.push(p); } return out; }

const keep = new Set(Array.from({ length: 20 }, (_, i) => i + 72));
for (const file of [...walk('src'), 'index.html']) for (const ch of readFileSync(file, 'utf8')) {
  const cp = ch.codePointAt(0); if (cp < 0x80) continue;
  const face = faces.find((f) => has(f, cp)); if (face) keep.add(face.index);
}
const rules = faces.filter((f) => keep.has(f.index)).map((f) =>
  `@font-face{font-family:'Pretendard Variable';font-style:normal;font-display:swap;font-weight:400 700;src:url(../../node_modules/pretendard/dist/web/variable/woff2-dynamic-subset/PretendardVariable.subset.${f.index}.woff2) format('woff2-variations');unicode-range:${f.range}}`);
const header = `/* Generated by scripts/build-fonts-css.mjs — do not edit. Pretendard © Kil Hyung-jin, SIL OFL 1.1 (https://github.com/orioncactus/pretendard). Slices: ${[...keep].sort((a, b) => a - b).join(',')} of 0–91. */\n`;
writeFileSync('src/styles/pretendard-subset.css', header + rules.join('\n') + '\n');
console.log(`wrote ${rules.length} faces`);
